#!/usr/bin/env node
// Regenerates the STUBS badge-data file for the combined 341-peak / 7-list
// dataset (ADK 46, CA 14ers/13ers, Catskill 3500, NE 67, NH 48, US State
// Highpoints), and reconciles the local dev DB against it for testing.
//
// The actual mountains/peak_lists/memberships/mountain_photos reconciliation
// (server/src/utils/multilistSeed.js) runs automatically on every server
// boot -- production's DB is only reachable over HTTP, so a one-off script
// like this can never touch it directly. This script exists for: (a) local
// dev/testing against a throwaway DB, and (b) regenerating
// generated-multilist-2026-badges.js when all_peaks.csv changes.
//
// Usage: node import-multilist.js

const fs = require('fs');
const path = require('path');
const { initDb, getDb, getLastMultilistResults } = require('../src/db');

function main() {
  // initDb() already runs the reconciliation once as part of normal boot
  // (see db.js) -- calling seedMultilist again here would just see
  // everything already present and report nothing, so this reads back the
  // results from that one real call instead of re-running it.
  initDb();
  const db = getDb();
  const results = getLastMultilistResults();

  const stubs = [];
  let inserted = 0, reused = 0;

  for (const r of results) {
    r.inserted ? inserted++ : reused++;
    // Only emit badge-art data for mountains this reconciliation actually
    // created. A "reused" row (e.g. Mount Elbert, matched as the same peak
    // as the existing Colorado 14er) already has a badge from whatever
    // batch created it.
    if (!r.inserted) continue;
    const peakId = r.row.id.slice(0, 60);
    // "full" has to be the name actually written to the DB (which may
    // carry a "(State)" disambiguation suffix) -- badge lookup-by-name has
    // to match what's actually stored. "name" stays the bare peak name for
    // the card's big headline text: a suffixed full name like "MOUNT MARCY
    // (NEW YORK)" is fine at the small size the badge plate renders it at,
    // but overflows badly at headline size, and the elevation/range line
    // right underneath already says the state.
    const shortNameUpper = r.row.name.replace(/["]/g, '').toUpperCase();
    const fullNameUpper = r.resolvedName.replace(/["]/g, '').toUpperCase();
    if (!r.stateAbbr) throw new Error(`No abbreviation mapped for state "${r.row.state}" (peak ${r.row.id})`);
    stubs.push([peakId, shortNameUpper, fullNameUpper, r.elevation.toLocaleString('en-US'), r.paletteKey, r.stateAbbr]);
  }

  console.log(`Mountains: ${inserted} inserted, ${reused} reused (already present, e.g. Mount Elbert)`);
  const byList = {};
  for (const r of results) for (const l of r.lists) byList[l] = (byList[l] || 0) + 1;
  for (const [k, v] of Object.entries(byList)) console.log(`  ${k}: ${v} members`);

  const badgeModule = `// GENERATED by server/scripts/import-multilist.js -- do not hand-edit.
// STUBS-shaped entries for the combined 341-peak / 7-list import (ADK 46,
// CA 14ers/13ers, Catskill 3500, NE 67, NH 48, US State Highpoints).
// Regenerate by re-running this script (against a DB that has these peaks
// reconciled -- e.g. after a fresh boot), not by editing this file directly.
//
// Deliberately no DB_ID_TO_PEAK_ID here, unlike the older Colorado 13ers
// batch: a numeric mountain_id -> peak-slug snapshot is only valid for the
// exact DB it was generated against. This script runs against whatever dev
// DB happens to be on hand, which will never have the same pre-existing
// row count as production, so any such snapshot would be silently wrong --
// every id shifted by however many rows differ, pointing each mountain at
// some other peak's badge. server/src/routes/badges.js resolves these
// peaks by a live mountains.name lookup instead, which has no such issue.
module.exports = {
  STUBS: ${JSON.stringify(stubs)},
  DB_ID_TO_PEAK_ID: {},
};
`;
  const badgeOutPath = path.resolve(__dirname, '../src/data/generated-multilist-2026-badges.js');
  fs.writeFileSync(badgeOutPath, badgeModule);
  console.log(`Wrote badge data for ${stubs.length} peaks to ${badgeOutPath}`);

  const { c: totalMountains } = db.prepare('SELECT COUNT(*) c FROM mountains').get();
  console.log(`Done. mountains table now has ${totalMountains} rows.`);
}

main();
